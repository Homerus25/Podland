package quadlets

import (
	"fmt"
	"strings"

	appErrors "github.com/Homerus25/podland/backend/internal/errors"
	"go.podman.io/podman/v6/pkg/domain/entities"
)

// generateEngine is the generate module's caller-width slice of the engine
// seam: the two inspect methods the conversion ritual reads, and nothing
// else. QuadletEngine satisfies it implicitly; the narrow width lets the
// module's tests drive the dispatch over the function-field fake engine
// without arming the whole domain engine.
type generateEngine interface {
	InspectContainer(id string) ([]*entities.ContainerInspectReport, []error, error)
	InspectPod(id string) ([]*entities.PodInspectReport, []error, error)
}

// resourceType is the vocabulary of source resources the generate module
// converts to quadlet text (architecture review 2026-10-19, candidate C7):
// each type carries its own inspection, name extraction, and conversion
// rules, so the dispatch's switch-case lives in this module instead of the
// service file.
type resourceType string

const (
	resourceTypeContainer resourceType = "container"
	resourceTypePod       resourceType = "pod"
)

// ConvertToQuadlet is the generate module's one entry point (architecture
// review 2026-10-19, candidate C7): it inspects the source resource on the
// handed engine and converts the inspect report to quadlet text, answering
// the quadlet's name and content. The error mapping lives here and keeps
// the domain's sentinels — an inspect failure or an empty report answers
// the resource's not-found sentinel, a conversion failure answers
// ErrQuadletGenerationFailed, and an unknown resource type answers
// ErrInvalidRequest. No new codes, no wire change.
func ConvertToQuadlet(engine generateEngine, rt resourceType, resourceID string) (string, string, error) {
	switch rt {
	case resourceTypeContainer:
		reports, _, err := engine.InspectContainer(resourceID)
		return inspectAndConvert(reports, err, resourceID, appErrors.ErrContainerNotFound,
			func(r *entities.ContainerInspectReport) string { return r.Name },
			generateContainerQuadlet)
	case resourceTypePod:
		reports, _, err := engine.InspectPod(resourceID)
		return inspectAndConvert(reports, err, resourceID, appErrors.ErrPodNotFound,
			func(r *entities.PodInspectReport) string { return r.Name },
			generatePodQuadlet)
	default:
		return "", "", appErrors.ErrInvalidRequest
	}
}

// inspectAndConvert runs the shared half of the conversion ritual — the
// empty-report guard, the name fallback to the resource id, the conversion,
// and the sentinel mapping. The container and pod cases of ConvertToQuadlet
// differ only in what rides in here: the not-found sentinel, the name
// extraction, and the converter.
func inspectAndConvert[T any](reports []T, inspectErr error, resourceID string, notFound error, nameOf func(T) string, convert func(T) (string, error)) (string, string, error) {
	if inspectErr != nil {
		return "", "", notFound
	}
	if len(reports) == 0 {
		return "", "", notFound
	}

	quadletName := nameOf(reports[0])
	if quadletName == "" {
		quadletName = resourceID
	}

	content, err := convert(reports[0])
	if err != nil {
		return "", "", appErrors.ErrQuadletGenerationFailed
	}
	return quadletName, content, nil
}

// generateContainerQuadlet converts a container inspect report to quadlet format.
// This implements the conversion logic from podman's pkg/systemd/quadlet package.
func generateContainerQuadlet(inspect *entities.ContainerInspectReport) (string, error) {
	if inspect == nil || inspect.Config == nil {
		return "", fmt.Errorf("invalid container inspect data")
	}

	var builder strings.Builder

	quadletName := inspect.Name
	if quadletName == "" {
		return "", fmt.Errorf("container name is required")
	}

	fmt.Fprintf(&builder, "# Generated by Podland from container %s\n", quadletName)
	fmt.Fprintf(&builder, "[Unit]\n")
	fmt.Fprintf(&builder, "Description=Podman container %s\n\n", quadletName)

	fmt.Fprintf(&builder, "[Container]\n")
	fmt.Fprintf(&builder, "ContainerName=%s\n", quadletName)

	if inspect.Config.Image != "" {
		fmt.Fprintf(&builder, "Image=%s\n", inspect.Config.Image)
	}

	if len(inspect.Config.Env) > 0 {
		for _, env := range inspect.Config.Env {
			fmt.Fprintf(&builder, "Environment=%s\n", env)
		}
	}

	if inspect.HostConfig != nil {
		if inspect.HostConfig.RestartPolicy != nil {
			policy := inspect.HostConfig.RestartPolicy.Name
			if policy != "" && policy != "no" {
				fmt.Fprintf(&builder, "RestartPolicy=%s\n", policy)
			}
		}

		if len(inspect.HostConfig.PortBindings) > 0 {
			builder.WriteString("PublishPort=")
			var ports []string
			for containerPort, bindings := range inspect.HostConfig.PortBindings {
				for _, binding := range bindings {
					ports = append(ports, fmt.Sprintf("%s:%s", binding.HostPort, containerPort))
				}
			}
			builder.WriteString(strings.Join(ports, ","))
			builder.WriteString("\n")
		}

		if len(inspect.HostConfig.Binds) > 0 {
			for _, bind := range inspect.HostConfig.Binds {
				fmt.Fprintf(&builder, "Volume=%s\n", bind)
			}
		}

		if len(inspect.HostConfig.NetworkMode) > 0 {
			fmt.Fprintf(&builder, "Network=%s\n", inspect.HostConfig.NetworkMode)
		}
	}

	if inspect.Config.Labels != nil {
		for key, value := range inspect.Config.Labels {
			fmt.Fprintf(&builder, "Label=%s=%s\n", key, value)
		}
	}

	return builder.String(), nil
}

// generatePodQuadlet converts a pod inspect report to quadlet format.
// This implements the conversion logic from podman's pkg/systemd/quadlet package.
func generatePodQuadlet(inspect *entities.PodInspectReport) (string, error) {
	if inspect == nil {
		return "", fmt.Errorf("invalid pod inspect data")
	}

	var builder strings.Builder

	podName := inspect.Name
	if podName == "" {
		return "", fmt.Errorf("pod name is required")
	}

	fmt.Fprintf(&builder, "# Generated by Podland from pod %s\n", podName)
	fmt.Fprintf(&builder, "[Unit]\n")
	fmt.Fprintf(&builder, "Description=Podman pod %s\n\n", podName)

	fmt.Fprintf(&builder, "[Pod]\n")
	fmt.Fprintf(&builder, "PodName=%s\n", podName)

	if len(inspect.CreateCommand) > 0 {
		builder.WriteString("PodmanArgs=")
		builder.WriteString(strings.Join(inspect.CreateCommand, " "))
		builder.WriteString("\n")
	}

	if len(inspect.Labels) > 0 {
		for key, value := range inspect.Labels {
			fmt.Fprintf(&builder, "Label=%s=%s\n", key, value)
		}
	}

	return builder.String(), nil
}
